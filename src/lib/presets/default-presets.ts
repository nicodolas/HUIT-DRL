/**
 * Returns the immediate static baseline presets (0ms latency, 100% offline).
 */
export function getDefaultPresets(): DrlCriteriaPreset[] {
  return DEFAULT_HUIT_PRESETS;
}

/**
 * Merges baseline presets with custom/overridden presets from Database or Local Storage.
 */
export function mergeWithCustomPresets(
  customPresets: DrlCriteriaPreset[] = []
): DrlCriteriaPreset[] {
  if (!customPresets || customPresets.length === 0) {
    return DEFAULT_HUIT_PRESETS;
  }

  const map = new Map<string, DrlCriteriaPreset>();
  for (const p of DEFAULT_HUIT_PRESETS) {
    map.set(p.code, p);
  }
  for (const p of customPresets) {
    map.set(p.code, p);
  }

  return Array.from(map.values()).sort((a, b) => {
    if (a.category !== b.category) return a.category - b.category;
    return a.code.localeCompare(b.code);
  });
}

